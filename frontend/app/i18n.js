export function loadLocale() {
  return normalizeLocale(localStorage.getItem(LANGUAGE_KEY));
}

export function saveLocale(locale) {
  const next = normalizeLocale(locale);
  localStorage.setItem(LANGUAGE_KEY, next);
  return next;
}

export function normalizeLocale(locale) {
  return locale === "en" ? "en" : "ko";
}

export function t(locale, key, params = {}) {
  const normalized = normalizeLocale(locale);
  const template = strings[normalized]?.[key] || strings.ko[key];
  if (!template) {
    missingKeys.add(`${normalized}:${key}`);
    if (typeof console !== "undefined" && console.warn) {
      console.warn(`missing i18n key: ${normalized}:${key}`);
    }
    return interpolate(key, params);
  }
  return interpolate(template, params);
}

export function hasI18nKey(locale, key) {
  const normalized = normalizeLocale(locale);
  return Boolean(strings[normalized]?.[key] || strings.ko[key]);
}

export function collectMissingI18nKeys() {
  return [...missingKeys].sort();
}

export function clearMissingI18nKeys() {
  missingKeys.clear();
}

export function routeKeyToLabelKey(key) {
  return ROUTE_LABEL_KEYS[key] || "";
}

export function fieldLabel(key, locale = "ko") {
  const labelKey = FIELD_LABEL_KEYS[key] || `field.${toCamelKey(key)}`;
  if (hasI18nKey(locale, labelKey)) return t(locale, labelKey);
  return humanizeKey(key, locale);
}

export function statusLabel(value, locale = "ko") {
  if (value === null || value === undefined || value === "") return "-";
  const normalized = String(value).trim().toUpperCase();
  const labelKey = STATUS_LABEL_KEYS[normalized];
  if (labelKey) return t(locale, labelKey);
  return humanizeStatus(value, locale);
}

export function localizeRouteMeta(meta, locale = "ko") {
  return {
    ...meta,
    group: translateMetaLabel(meta?.groupKey || meta?.group, locale),
    title: translateMetaLabel(meta?.titleKey || meta?.title, locale),
  };
}

export function labelForNode(node, locale) {
  const normalized = normalizeLocale(locale);
  const labels = node?.labels || {};
  if (normalized === "en") {
    return labels.en || node?.label_en || node?.name_en || node?.label || node?.display_name || node?.name || node?.code || "";
  }
  return labels.ko || node?.label_ko || node?.label || node?.display_name || node?.name || node?.code || "";
}

export function routeLabelsFromMenu(tree, key, locale, fallbackMeta) {
  const fallback = localizeRouteMeta(fallbackMeta, locale);
  const path = findMenuPath(tree, key);
  if (!path.length) return fallback;
  const activeNode = path[path.length - 1];
  const rootNode = path.find((node) => TOP_LEVEL_KEYS.has(node.code)) || path[1] || activeNode;
  return {
    ...fallback,
    group: labelForNode(rootNode, locale) || fallback.group,
    title: labelForNode(activeNode, locale) || fallback.title,
  };
}

export function leafFocusText(locale, key, delegate) {
  return t(locale, "leaf.focus", {
    key: escapeHtml(key),
    delegate: escapeHtml(delegate),
  });
}

function translateMetaLabel(value, locale) {
  if (typeof value === "function") return value(locale);
  if (typeof value === "string" && hasI18nKey(locale, value)) return t(locale, value);
  return value || "";
}

function interpolate(template, params) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? ""));
}

function findMenuPath(node, key, ancestors = []) {
  if (!node) return [];
  const path = [...ancestors, node];
  if (node.code === key || node.key === key) return path;
  const children = Array.isArray(node.children) ? node.children : [];
  for (const child of children) {
    const found = findMenuPath(child, key, path);
    if (found.length) return found;
  }
  return [];
}

function toCamelKey(key) {
  return String(key || "").replace(/_([a-z])/g, (_, char) => char.toUpperCase());
}

function humanizeKey(key, locale) {
  const words = String(key || "").replaceAll("_", " ");
  if (normalizeLocale(locale) === "ko") return words;
  return words.replace(/\b\w/g, (char) => char.toUpperCase());
}

function humanizeStatus(value, locale) {
  const text = String(value || "").replaceAll("_", " ").toLowerCase();
  if (normalizeLocale(locale) === "ko") return String(value || "-");
  return text.replace(/\b\w/g, (char) => char.toUpperCase());
}
